// Writes src/schema/time-zones.ts: every IANA time zone name, as a type, so the editor suggests a name for `system.timezone` and refuses one that does not exist. Run it again when the runtime learns new zones.

import { writeFileSync } from "node:fs";

class TimeZones {
    private static readonly OUTPUT = new URL("../src/schema/time-zones.ts", import.meta.url);

    /**
     * Names the runtime accepts but does not list. Its list keeps some zones under an older name, such as `Asia/Calcutta` for `Asia/Kolkata`, and leaves out links, such as `Etc/UTC`. Each is checked against the runtime before it is written.
     */
    private static readonly UNLISTED = [
        "Africa/Asmara",
        "America/Argentina/Buenos_Aires",
        "America/Argentina/Catamarca",
        "America/Argentina/Cordoba",
        "America/Argentina/Jujuy",
        "America/Argentina/Mendoza",
        "America/Atikokan",
        "America/Indiana/Indianapolis",
        "America/Kentucky/Louisville",
        "America/Nuuk",
        "Asia/Chongqing",
        "Asia/Ho_Chi_Minh",
        "Asia/Kathmandu",
        "Asia/Kolkata",
        "Asia/Yangon",
        "Atlantic/Faroe",
        "Australia/Canberra",
        "Etc/GMT",
        "Etc/UTC",
        "Europe/Kyiv",
        "Pacific/Chuuk",
        "Pacific/Kanton",
        "Pacific/Pohnpei",
    ];

    static main(): void {
        for (const zone of TimeZones.UNLISTED) {
            if (!TimeZones.isKnown(zone)) throw new Error(`the runtime does not know ${zone}`);
        }

        const listed = Intl.supportedValuesOf("timeZone");
        const zones = [...new Set([...listed, ...TimeZones.UNLISTED])].filter((zone) => zone !== "UTC").sort();

        const page = [
            "// Generated by `bun scripts/time-zones.ts` from the time zones the runtime knows. Do not edit by hand: run the script again to update it.",
            "",
            "/** An IANA time zone name, such as `Asia/Jakarta`, or `UTC`. */",
            "export type TimeZone =",
            ...["UTC", ...zones].map((zone, index, all) => `    | "${zone}"${index === all.length - 1 ? ";" : ""}`),
            "",
        ].join("\n");

        writeFileSync(TimeZones.OUTPUT, page);
        console.log(`src/schema/time-zones.ts written, ${zones.length + 1} zones`);
    }

    private static isKnown(zone: string): boolean {
        try {
            new Intl.DateTimeFormat("en-US", { timeZone: zone });
            return true;
        } catch {
            return false;
        }
    }
}

TimeZones.main();
